"""Generates src/serve/quality_table.h (the quality label of every K/V format on every tier) from the quality gate's results.

Usage: python -I tools/gen_quality_table.py [build/bench/quality/kv_formats.json]

Rows come from bench/quality_gate.py (teacher-forced top-1 agreement and KL divergence against the FP32 reference). Workloads: english, code, structured,
long1500, long8k; Tamil is excluded (not part of Dara's target use). The label rule is the gate's own (bench/quality_gate.py: label()).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "bench", "quality", "kv_formats.json")
WORKLOADS = ["english", "code", "structured", "long1500", "long8k"]
TIERS = {"nano": "dara-nano", "4b": "dara-core-4b", "9b": "dara-pro-9b"}
FORMATS = {"int8_q8kv": "q8", "int8_k8v4kv": "k8v4", "int8_q4kv": "q4", "int8_tq4kv": "tq4"}
ORDER = {"high": 0, "medium": 1, "lower": 2}


def label(x):
    clear = (x["positions"] - x["top1"] - x["near_tie_flips"]) * 128.0 / x["positions"]
    if clear <= 2 and x["kl_mean"] <= 0.015: return "high"
    if clear <= 6 and x["kl_mean"] <= 0.05: return "medium"
    return "lower"


r = json.load(open(SRC))
rows = []
for tier, mid in TIERS.items():
    for tag, kv in FORMATS.items():
        worst, min_top1, worst_clear, worst_kl, n = "high", 128.0, 0.0, 0.0, 0
        for w in WORKLOADS:
            x = r.get(f"{tier}/{w}/{tag}")
            if not x or "error" in x:
                worst = "lower"
                continue
            n += 1
            l = label(x)
            if ORDER[l] > ORDER[worst]: worst = l
            min_top1 = min(min_top1, x["top1"] * 128.0 / x["positions"])
            worst_clear = max(worst_clear, (x["positions"] - x["top1"] - x["near_tie_flips"]) * 128.0 / x["positions"])
            worst_kl = max(worst_kl, x["kl_mean"])
        if n == 0:
            continue
        rows.append((mid, kv, worst, min_top1, worst_clear, worst_kl, n))

out = ["// Generated by tools/gen_quality_table.py from the quality gate (bench/quality_gate.py): top-1 agreement (of 128 positions) and KL divergence against the",
       "// FP32 reference, worst case over the workloads english, code, structured, long1500 and long8k. Do not edit; rerun the script after a new gate run.",
       "#pragma once",
       "",
       "namespace dara::serve {",
       "",
       "struct QualityRow { const char* model; const char* kv; const char* label; double min_top1_of_128, worst_clear_errors, worst_kl; int workloads; };",
       "inline constexpr QualityRow kQualityTable[] = {"]
for mid, kv, lab, t1, wc, kl, n in rows:
    out.append(f'    {{"{mid}", "{kv}", "{lab}", {t1:.1f}, {wc:.1f}, {kl:.5f}, {n}}},')
out += ["};", "", "}  // namespace dara::serve", ""]
path = os.path.join(ROOT, "src", "serve", "quality_table.h")
open(path, "w", newline="\n").write("\n".join(out))
print(f"wrote {path} ({len(rows)} rows)")
for row in rows:
    print("  %-13s %-5s %-6s min top-1 %.1f/128, worst clear errors %.1f, worst KL %.4f" % (row[0], row[1], row[2], row[3], row[4], row[5]))
