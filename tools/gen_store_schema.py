"""Generates src/serve/store_schema.h from docs/ui/db/schema.sql (schema version 1) and the migrations next to it (0002_*.sql, 0003_*.sql, ...).
The schema file is never edited after release: new tables and columns arrive as numbered migrations, applied forward-only by the server.
Usage: python -I tools/gen_store_schema.py   (rerun whenever schema.sql or a migration changes; the build does not do it for you)"""
import glob
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
db_dir = os.path.join(root, "docs", "ui", "db")


def read(path):
    return open(path, encoding="utf8").read().replace("\r\n", "\n")


sql = read(os.path.join(db_dir, "schema.sql"))
assert ')SQL"' not in sql
migrations = sorted(glob.glob(os.path.join(db_dir, "[0-9][0-9][0-9][0-9]_*.sql")))
for i, path in enumerate(migrations):
    # 0002 upgrades version 1 -> 2, 0003 upgrades 2 -> 3, ... no gaps
    assert int(re.match(r"(\d{4})_", os.path.basename(path)).group(1)) == i + 2, f"migration numbering: {os.path.basename(path)}"

out = ["// GENERATED by tools/gen_store_schema.py from docs/ui/db/*.sql -- do not edit.", "#pragma once", "", "namespace dara::serve {", "",
       "// Schema version 1 (PRAGMA user_version = 1 after it is applied).",
       'inline const char* const kStoreSchemaV1 = R"SQL(' + sql + ')SQL";', "",
       "// kStoreMigrationSql[i] upgrades schema version i+1 to i+2 (forward only). The latest schema version is 1 + the number of entries.",
       "inline const char* const kStoreMigrationSql[] = {"]
for path in migrations:
    body = read(path)
    assert ')SQL"' not in body
    out.append('    // ' + os.path.basename(path))
    out.append('    R"SQL(' + body + ')SQL",')
out += ["};", "inline constexpr int kStoreMigrationCount = static_cast<int>(sizeof(kStoreMigrationSql) / sizeof(kStoreMigrationSql[0]));", "", "}  // namespace dara::serve", ""]
open(os.path.join(root, "src", "serve", "store_schema.h"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print(f"wrote src/serve/store_schema.h (schema 1 + {len(migrations)} migration(s) -> version {1 + len(migrations)})")
