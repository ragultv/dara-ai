"""Generates src/serve/store_schema.h from docs/ui/db/schema.sql (the single source of the database schema).
Usage: python -I tools/gen_store_schema.py   (rerun whenever schema.sql changes; the build does not do it for you)"""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sql = open(os.path.join(root, "docs", "ui", "db", "schema.sql"), encoding="utf8").read().replace("\r\n", "\n")
assert ')SQL"' not in sql
out = ("// GENERATED by tools/gen_store_schema.py from docs/ui/db/schema.sql -- do not edit.\n#pragma once\n\nnamespace dara::serve {\n\n"
       "// Schema version 1 (PRAGMA user_version = 1 after it is applied).\ninline const char* const kStoreSchemaV1 = R\"SQL(" + sql + ")SQL\";\n\n}  // namespace dara::serve\n")
open(os.path.join(root, "src", "serve", "store_schema.h"), "w", encoding="utf8", newline="\n").write(out)
print("wrote src/serve/store_schema.h")
