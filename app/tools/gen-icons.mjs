// Generates src/lib/ui/icon-map.ts: only the lucide icons the source mentions (as quoted kebab-case strings), so the bundle does not carry the whole
// icon library. Run by `prebuild`; rerun after adding an icon name anywhere in src/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as lucide from "lucide-react";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "..", "src");
const skip = new Set(["icon-map.ts"]);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(tsx?|ts)$/.test(e.name) && !skip.has(e.name)) out.push(p);
  }
  return out;
}

const pascal = (s) =>
  s
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
const found = new Set();
for (const file of walk(src)) {
  const text = fs.readFileSync(file, "utf8");
  for (const m of text.matchAll(/["']([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["']/g)) {
    const name = m[1];
    if (
      pascal(name) in lucide &&
      typeof lucide[pascal(name)] !== "undefined" &&
      /^[A-Z]/.test(pascal(name))
    )
      found.add(name);
  }
}
const names = [...found].sort();
const lines = [
  "// GENERATED by tools/gen-icons.mjs; do not edit by hand.",
  'import type { ComponentType } from "react";',
  `import { ${names.map((n) => pascal(n)).join(", ")} } from "lucide-react";`,
  "",
  "export type IconComponent = ComponentType<{ size?: number | string; className?: string }>;",
  "",
  "export const ICONS: Record<string, IconComponent> = {",
  ...names.map((n) => `  "${n}": ${pascal(n)},`),
  "};",
  ""
];
fs.writeFileSync(path.join(src, "lib", "ui", "icon-map.ts"), lines.join("\n"));
console.log(`icon-map.ts: ${names.length} icons`);
